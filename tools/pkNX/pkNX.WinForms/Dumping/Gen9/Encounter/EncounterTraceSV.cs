using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.Json;

namespace pkNX.Structures.FlatBuffers;

/// <summary>
/// OFF by default. A deterministic JSONL diagnostic stream for original SV 4.0.0
/// source-to-encounter attribution. All emitted values are observations, never
/// used to change PKHeX .pkl bytes or the native encounter algorithm.
/// </summary>
public static class EncounterTraceSV
{
    private static StreamWriter? writer;
    private static readonly Dictionary<string, int> Counts = new(StringComparer.Ordinal);
    private static readonly HashSet<(int Location, int Species)> WildTargets = [];
    private static readonly HashSet<int> FixedTargets = [];
    private static readonly HashSet<int> WildSpecies = [];

    public static bool Enabled => writer is not null;

    public static void Enable(string targetDirectory, string jsonlFile)
    {
        if (writer is not null)
            throw new InvalidOperationException("Gen9 encounter trace already enabled");
        WildTargets.Clear();
        FixedTargets.Clear();
        WildSpecies.Clear();
        Counts.Clear();
        string wild = Path.Combine(targetDirectory, "wild_level_range_pairs.csv");
        string fix = Path.Combine(targetDirectory, "fixed_158_counterfactual_pairs.csv");
        int w = LoadTargets(wild, (row) =>
        {
            int species = int.Parse(row["species_national"]);
            int location = int.Parse(row["location_id"]);
            int cross = int.Parse(row["cross_from_id"]);
            WildSpecies.Add(species);
            WildTargets.Add((location, species));
            if (cross != 0)
                WildTargets.Add((cross, species));
        });
        int f = LoadTargets(fix, row => FixedTargets.Add(int.Parse(row["species_national"])));
        if (w != 666 || f != 189 || WildTargets.Count == 0 || FixedTargets.Count == 0)
            throw new InvalidDataException($"Original source-attested target set must be 666 wild and 189 fixed, got {w} and {f}");
        Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(jsonlFile))!);
        writer = new StreamWriter(jsonlFile, false, new UTF8Encoding(false), 65536);
        Write(new {
            stage = "trace_start", source = "SV_4_0_0_original_game_pkNX",
            wildTargetRows = w, fixedTargetRows = f,
            targetPairs = WildTargets.Count, fixedSpecies = FixedTargets.Count,
            claim = "SOURCE_CANDIDATE_TRACE_NOT_LEGALITY_OR_RNG_PROOF",
        });
    }

    private static int LoadTargets(string path, Action<Dictionary<string, string>> collect)
    {
        if (!File.Exists(path))
            throw new FileNotFoundException("Native-vs-PKHeX original review CSV missing", path);
        using var reader = new StreamReader(path, Encoding.UTF8);
        var header = reader.ReadLine()?.TrimStart('\uFEFF').Split(',') ??
                     throw new InvalidDataException("Source triage CSV has no header");
        var keys = new HashSet<string>(header, StringComparer.Ordinal);
        if (!keys.Contains("species_national"))
            throw new InvalidDataException("Original source triage CSV lacks national species index");
        if (Path.GetFileName(path).StartsWith("wild_", StringComparison.Ordinal) &&
            (!keys.Contains("location_id") || !keys.Contains("cross_from_id")))
            throw new InvalidDataException("Wild source triage CSV lacks actual location/crossover indexes");
        int count = 0;
        while (reader.ReadLine() is { } line)
        {
            if (string.IsNullOrWhiteSpace(line))
                continue;
            // Input is machine-generated by the pinned numeric-only triage writer.
            // Quote or comma in any value would make a plain split ambiguous -> fail closed.
            if (line.IndexOf('"') >= 0)
                throw new InvalidDataException("Quoted CSV value not allowed for numeric trace target keys");
            var values = line.Split(',');
            if (values.Length != header.Length)
                throw new InvalidDataException($"Malformed source triage CSV numeric row #{count+1}");
            var row = new Dictionary<string, string>(StringComparer.Ordinal);
            for (int i = 0; i < values.Length; i++)
                row.Add(header[i], values[i]);
            collect(row);
            count++;
        }
        return count;
    }

    public static bool Wild(int location, int species) =>
        writer is not null && WildSpecies.Contains(species) && WildTargets.Contains((location, species));

    public static bool Fixed(int species) =>
        writer is not null && FixedTargets.Contains(species);

    public static void Write(object data)
    {
        if (writer is null) return;
        string json = JsonSerializer.Serialize(data);
        writer.WriteLine(json);
        // All traces are diagnostic only; writing must never change game/pkNX output.
        // I/O failures are intentionally fatal, instead of reporting incomplete provenance.
        using var doc = JsonDocument.Parse(json);
        if (doc.RootElement.TryGetProperty("stage", out var stage))
        {
            string name = stage.GetString() ?? "unknown";
            Counts[name] = Counts.GetValueOrDefault(name) + 1;
        }
    }

    public static void Close(string? manifestPath = null, bool completed = true)
    {
        if (writer is null) return;
        Write(new { stage="trace_finished", eventCounts=Counts,
                    status=completed ? "REAL_NATIVE_POINT_PROVENANCE_RECORDED_NOT_GAME_RUNTIME_PROVED" :
                                       "PARTIAL_NATIVE_TRACE_INCOMPLETE_NOT_EVIDENCE" });
        writer.Dispose();
        writer = null;
        if (manifestPath is not null)
        {
            Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(manifestPath))!);
            File.WriteAllText(manifestPath,
                JsonSerializer.Serialize(new {
                    status=completed ? "ORIGINAL_NATIVE_ENCOUNTER_TRACE_TARGETED_COMPLETE" : "PARTIAL_OR_BLOCKED_TRACE",
                    source="Source SHA verified by separate native encounter manifest",
                    eventCounts=Counts,
                    caution="No game-captured PK9 or runtime encounter claims; no native .pkl modified"
                }, new JsonSerializerOptions { WriteIndented=true })+"\n",
                new UTF8Encoding(false));
        }
    }
}
